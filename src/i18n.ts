const dictionaries = { en, fr } as const;
export type Lang = keyof typeof dictionaries;

function detect(): Lang {
  const stored = localStorage.getItem('maillo.lang');
  if (stored === 'en' || stored === 'fr') return stored;
  if (config.language !== 'auto') return config.language;
  return navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export let lang: Lang = detect();
document.documentElement.lang = lang;

export function setLanguage(next: Lang | 'auto') {
  if (next === 'auto') localStorage.removeItem('maillo.lang');
  else localStorage.setItem('maillo.lang', next);
  location.reload();
}

export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[lang][key] ?? en[key] ?? key;
  if (s.includes('|') && vars && typeof vars.n === 'number') {
    const [one, many] = s.split('|');
    s = vars.n === 1 ? one : many;
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const locale = () => {
  const nav = navigator.language || lang;
  return nav.toLowerCase().startsWith(lang) ? nav : lang;
};
